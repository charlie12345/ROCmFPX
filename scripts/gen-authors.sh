#!/usr/bin/env bash

# master in llama.cpp, main in forks such as this one
branch=master
git rev-parse --verify -q "$branch" > /dev/null || branch=main

printf "# date: $(date)\n" > AUTHORS
printf "# this file is auto-generated by scripts/gen-authors.sh\n\n" >> AUTHORS

git log --format='%an <%ae>' --reverse --date=short "$branch" | awk '!seen[$0]++' | sort >> AUTHORS

# if necessary, update your name here. for example: jdoe -> John Doe
# (-i.bak works with both GNU and BSD sed)
sed -i.bak 's/^jdoe/John Doe/g' AUTHORS && rm -f AUTHORS.bak
